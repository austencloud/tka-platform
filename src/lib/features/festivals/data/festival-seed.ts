import type { FestivalRegion, FestivalSize } from "../domain/models/festival";

// Seed type uses ISO strings instead of Firestore Timestamps.
// The seeding script converts these to Timestamps at write time.
export interface FestivalSeed {
  name: string;
  organizationId: string;
  organization: string;
  location: {
    venue?: string;
    city: string;
    state?: string;
    country: string;
    coordinates: { lat: number; lng: number };
  };
  startDate: string;
  endDate: string;
  applicationDeadline?: string;
  applicationUrl?: string;
  applicationContact?: string;
  seekingInstructors: boolean;
  seekingPerformers: boolean;
  description: string;
  websiteUrl?: string;
  imageUrl?: string;
  socialLinks?: { instagram?: string; facebook?: string };
  estimatedSize?: FestivalSize;
  region: FestivalRegion;
  tags: string[];
}

// Derived from organization name: lowercase, spaces → hyphens, punctuation stripped.
function toOrgId(org: string): string {
  return org
    .toLowerCase()
    .replace(/['']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

// Map "small" (used in source data) to "intimate" to satisfy the FestivalSize union.
function toSize(raw: string | null): FestivalSize | undefined {
  if (!raw) return undefined;
  if (raw === "small") return "intimate";
  return raw as FestivalSize;
}

