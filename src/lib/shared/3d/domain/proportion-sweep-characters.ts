import { AVATAR_DEFINITIONS } from "@austencloud/scene-3d";
import type { CharacterDefinition, CharacterId } from "./character-model";

/**
 * A controlled body-proportion sweep for the staff-grip lab.
 *
 * The twelve deployed catalog rigs vary every dimension at once, so when one
 * fails the hug fit there is no way to say whether stature, arm length or
 * shoulder span caused it. Four of the twelve already fail. These ten bodies
 * are one licensed base rig (`ch12`, the catalog median for reach) with exactly
 * one dimension moved per body, so a failure names its own cause.
 *
 * Generated by `pnpm run characters:proportion-sweep`. The GLBs live under
 * `static/models/avatars/proportion-sweep/`, which is gitignored in full, so a
 * checkout without them simply has no sweep. Every entry is
 * `availability: "local-evaluation"` and none can reach a production build or
 * the deployed CDN catalog.
 *
 * The measured block is what the runtime reports, not what the parameters
 * intended: it is read off each GLB's authored rest pose through the same
 * `AvatarSkeletonBuilder` mapping and the same `performer-reach-measurements`
 * arithmetic the browser uses, so a body that claims to be tall and measures
 * median is caught rather than shipped.
 */
export interface ProportionSweepCharacter extends CharacterDefinition {
  /** The single dimension this body moves away from the median. */
  axis:
    | "none"
    | "stature"
    | "shoulderWidth"
    | "armLength"
    | "armSegmentRatio"
    | "torsoGirth";
  /** Multipliers handed to the Blender rescale stage; empty for the median. */
  parameters: Readonly<Record<string, number>>;
  /** What the solve actually measures off this body. Centimetres. */
  measured: {
    statureCm: number;
    upperArmCm: number;
    forearmCm: number;
    reachCm: number;
    shoulderWidthCm: number;
    /**
     * Lateral foot separation. Not a solve input, a tripwire. A Blender bake
     * that freezes the catalog rigs' Mixamo clip instead of their bind pose
     * collapses this onto the hip separation, and nothing else here notices.
     */
    footSeparationCm: number;
    hugLaneCm: number;
    hugForwardCm: number;
    /** Recommended length when it fits, otherwise the maximum that would. */
    staffCm: number;
    staffFits: boolean;
  };
}

