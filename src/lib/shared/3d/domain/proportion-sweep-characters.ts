/**
 * Register the sweep with the catalog owner so the production load path can
 * resolve these ids.
 *
 * This mirrors how the lab already registers its intake rig: the sweep stays
 * out of the deployable catalog, and a local-only route opts in. Calling this
 * more than once is safe.
 */
export function registerProportionSweepCharacters(): readonly ProportionSweepCharacter[] {
  for (const character of PROPORTION_SWEEP_CHARACTERS) {
    if (AVATAR_DEFINITIONS.some(({ id }) => id === character.id)) continue;
    AVATAR_DEFINITIONS.push(character);
  }
  return PROPORTION_SWEEP_CHARACTERS;
}
