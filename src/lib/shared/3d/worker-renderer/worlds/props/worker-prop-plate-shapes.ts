import { Path, Shape } from "three";

type Cubic = readonly [number, number, number, number, number, number];

interface Contour {
  readonly start: readonly [number, number];
  readonly curves: readonly Cubic[];
}

function trace(
  target: Shape | Path,
  contour: Contour,
  scale: number,
  offset: readonly [number, number] = [0, 0],
  reverse = false
): Shape | Path {
  const turn = reverse ? -scale : scale;
  const x = (value: number) => (value - offset[0]) * turn;
  const y = (value: number) => (value - offset[1]) * turn;
  target.moveTo(x(contour.start[0]), y(contour.start[1]));
  for (const [c1x, c1y, c2x, c2y, endX, endY] of contour.curves) {
    target.bezierCurveTo(x(c1x), y(c1y), x(c2x), y(c2y), x(endX), y(endY));
  }
  target.closePath();
  return target;
}

