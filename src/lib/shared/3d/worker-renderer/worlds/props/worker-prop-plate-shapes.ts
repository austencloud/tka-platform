export const TRIQUETRA_RIBBON_WIDTH = 0.0542;

export function buildTriquetraShape(
  staffLength: number,
  variant: "triquetra" | "triquetra2"
): Shape {
  const grip =
    variant === "triquetra2"
      ? ({ offset: [0, 0.55261], reverse: true } as const)
      : ({ offset: [0, -0.02117], reverse: false } as const);
  const shape = trace(
    new Shape(),
    TRIQUETRA_OUTLINE,
    staffLength,
    grip.offset,
    grip.reverse
  ) as Shape;
  shape.holes = TRIQUETRA_HOLES.map(
    (hole) =>
      trace(new Path(), hole, staffLength, grip.offset, grip.reverse) as Path
  );
  return shape;
}

const EIGHTRINGS_OUTER = 68.25 / 252.8;
const EIGHTRINGS_INNER = 52.25 / 252.8;
const EIGHTRINGS_OFFSET = 60.25 / 252.8;
const EIGHTRINGS_CROSSING = Math.sqrt(
  EIGHTRINGS_OUTER * EIGHTRINGS_OUTER - EIGHTRINGS_OFFSET * EIGHTRINGS_OFFSET
);
const EIGHTRINGS_PHI = Math.atan2(EIGHTRINGS_OFFSET, EIGHTRINGS_CROSSING);

export const EIGHTRINGS_STOCK_WIDTH = EIGHTRINGS_OUTER - EIGHTRINGS_INNER;

export function buildEightringsShape(staffLength: number): Shape {
  const outer = EIGHTRINGS_OUTER * staffLength;
  const inner = EIGHTRINGS_INNER * staffLength;
  const offset = EIGHTRINGS_OFFSET * staffLength;
  const shape = new Shape();
  shape.absarc(
    0,
    offset,
    outer,
    -EIGHTRINGS_PHI,
    EIGHTRINGS_PHI + Math.PI,
    false
  );
  shape.absarc(
    0,
    -offset,
    outer,
    Math.PI - EIGHTRINGS_PHI,
    EIGHTRINGS_PHI + 2 * Math.PI,
    false
  );
  shape.closePath();
  shape.holes = [
    new Path().absarc(0, offset, inner, 0, 2 * Math.PI, false),
    new Path().absarc(0, -offset, inner, 0, 2 * Math.PI, false),
  ];
  return shape;
}
